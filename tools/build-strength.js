// Measures every kingdom card on its own: "Big Money + this card" vs plain Big Money,
// N games per variant (seats alternate). Writes js/strength-data.js.
// Run: node tools/build-strength.js [games]   (about a minute at 2000)
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('../js/cards.js');
const S = require('../js/sim.js');

const N = Number(process.argv[2]) || 2000;
const all = C.pool('mix');
const bm = S.bigMoney();
const byId = {}, byCard = {};
const t0 = Date.now();
for (const x of all) {
  const filler = all.filter(y => y !== x && y !== 'Gardens').slice(0, 9);
  const kingdom = [x].concat(filler);
  const ed = C.CARDS[x].ed === 1 ? 1 : 2;
  let variants = [];
  if (x === 'Gardens') {
    const kw = ['Gardens', 'Workshop'].concat(all.filter(y => y !== 'Gardens' && y !== 'Workshop').slice(0, 8));
    const w = S.versus(kw, S.gardens('Workshop'), bm, N, 4242, { edition: 2 });
    byId['gardens:Workshop'] = round(w);
    const kw1 = ['Gardens', 'Woodcutter'].concat(all.filter(y => y !== 'Gardens' && y !== 'Woodcutter').slice(0, 8));
    byId['gardens:Woodcutter'] = round(S.versus(kw1, S.gardens('Woodcutter'), bm, N, 4243, { edition: 1 }));
    byCard[x] = { id: 'gardens:Workshop', label: 'Workshop / Gardens rush', win: round(w) };
    continue;
  }
  if (S.withCard(x, 1).id.indexOf(':') < 0) variants = [S.withCard(x, 1)];
  else variants = [S.withCard(x, 1), S.withCard(x, 2)];
  let best = null;
  for (const v of variants) {
    const w = round(S.versus(kingdom, v, bm, N, 1000 + all.indexOf(x) * 13, { edition: ed }));
    byId[v.id] = w;
    if (!best || w > best.win) best = { id: v.id, label: v.label, win: w };
  }
  byCard[x] = best;
  process.stdout.write(x + ' ' + best.win + '  ');
}
function round(w) { return Math.round(w * 1000) / 1000; }
const out = '/* Generated by tools/build-strength.js on ' + new Date().toISOString().slice(0, 10) + ': ' + N +
  ' games per variant vs plain Big Money (seats alternate). Do not hand-edit. */\n' +
  '(function (root) {\n  var data = ' + JSON.stringify({ games: N, byId, byCard }) + ';\n' +
  '  if (typeof module === \'object\' && module.exports) module.exports = data; else root.DomStrength = data;\n' +
  '})(typeof self !== \'undefined\' ? self : this);\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'strength-data.js'), out);
console.log('\nwrote strength-data.js in ' + ((Date.now() - t0) / 1000).toFixed(1) + 's');
